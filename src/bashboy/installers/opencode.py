"""OpenCode installer: write the deny-only plugin and register it.

V2 registers through ``Plugin.define`` / ``ctx.tool.hook("execute.before")``; V1
used ``server()`` returning ``"tool.execute.before"``. Both delegate to the same
helper, so the verdict logic exists once.

The plugin never passes the command through a shell: it is one ``execFile`` argv
element with ``shell: false``. ENOENT, non-zero exit without JSON, invalid JSON,
and timeouts all throw (fail closed).
"""

from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

from .. import __version__
from ..config import ConfigError, load_config
from . import atomic_write_text

_PLUGIN_TEMPLATE = """/**
 * BashBoy plugin for OpenCode - deny-only shell command gate.
 *
 * Generated by `bashboy install --opencode` (bashboy VERSION_PLACEHOLDER). Re-run that
 * command to rewrite this file; change policy in ~/.bashboy/config.toml instead.
 *
 * Only a denial is expressed. An allow means "no objection" and lets the host's
 * normal permission flow continue.
 */
import { execFile } from "node:child_process"
import { promisify } from "node:util"
import { Plugin } from "@opencode/plugin"

const run = promisify(execFile)
const TIMEOUT_MS = TIMEOUT_MS_PLACEHOLDER
type AnyRecord = Record<string, any>

function isShellTool(tool: unknown): boolean {
  const id = String(tool ?? "").toLowerCase()
  return id === "bash" || id === "shell"
}

/**
 * Ask bashboy for a verdict and throw only when it says deny.
 * Any inability to get a clear verdict also throws (fail closed).
 */
async function classify(command: string, cwd: unknown): Promise<void> {
  const dir = typeof cwd === "string" && cwd.length > 0 ? cwd : process.cwd()
  let stdout = ""

  try {
    const result = await run(
      "uvx",
      ["bashboy", "check", "--json", "--command", command, "--cwd", dir],
      { shell: false, timeout: TIMEOUT_MS, windowsHide: true },
    )
    stdout = String((result as AnyRecord).stdout ?? "")
  } catch (error: any) {
    const fromError = String(error?.stdout ?? "")
    if (fromError.trim().length === 0) {
      const detail = error?.code ?? error?.message ?? "unknown error"
      throw new Error("BashBoy could not verify this command: " + String(detail))
    }
    // bashboy exits 1 for deny, so a valid deny payload arrives via error.stdout.
    stdout = fromError
  }

  let verdict: AnyRecord
  try {
    verdict = JSON.parse(stdout)
  } catch {
    throw new Error("BashBoy could not verify this command: invalid JSON from bashboy")
  }

  if (verdict?.decision === "deny") {
    throw new Error("BashBoy blocked this command: " + String(verdict?.reason ?? "denied"))
  }
  if (verdict?.decision === "allow") {
    return
  }
  throw new Error("BashBoy could not verify this command: unexpected verdict")
}

export default {
  ...Plugin.define({
    id: "bashboy",
    async setup(ctx: any) {
      await ctx.tool.hook("execute.before", async (event: any) => {
        if (!isShellTool(event?.tool)) return
        const input = event?.input ?? {}
        const command = input.command
        if (typeof command !== "string" || command.trim().length === 0) return
        await classify(command, input.cwd)
      })
    },
  }),

  // V1 fallback: same helper, different registration shape.
  async server() {
    return {
      "tool.execute.before": async (input: any, output: any) => {
        if (!isShellTool(input?.tool)) return
        const args = output?.args ?? {}
        const command = args.command
        if (typeof command !== "string" || command.trim().length === 0) return
        await classify(command, args.cwd)
      },
    }
  },
}
"""

PLUGIN_SOURCE = _PLUGIN_TEMPLATE.replace("VERSION_PLACEHOLDER", __version__).replace(
    "TIMEOUT_MS_PLACEHOLDER", "15000"
)


def default_config_dir() -> Path:
    return Path.home() / ".config" / "opencode"


def _same_path(left: str, right: str) -> bool:
    return os.path.normcase(os.path.abspath(left)) == os.path.normcase(os.path.abspath(right))


def _load_config(config_file: Path) -> dict:
    if not config_file.exists():
        return {"$schema": "https://opencode.ai/config.json"}
    try:
        raw = config_file.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"cannot read {config_file}: {exc}") from exc
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ConfigError(
            f"{config_file}: not valid JSON ({exc}); refusing to modify it"
        ) from exc
    if not isinstance(data, dict):
        raise ConfigError(f"{config_file}: expected a JSON object; refusing to modify it")
    return data


def install_opencode(config_dir: Path | str | None = None, *, dry_run: bool = False) -> dict:
    base = Path(config_dir) if config_dir else default_config_dir()
    plugin_path = base / "plugins" / "bashboy.ts"
    config_file = base / "opencode.json"
    plugin_target = str(plugin_path)

    cfg = load_config()
    source = _PLUGIN_TEMPLATE.replace("VERSION_PLACEHOLDER", __version__).replace(
        "TIMEOUT_MS_PLACEHOLDER", str(int(cfg.opencode.timeout_ms))
    )

    config = _load_config(config_file)
    # V2 documents ``plugins``; V1 used ``plugin``. Preserve whichever is already
    # there and never write both keys.
    if "plugins" in config:
        key = "plugins"
    elif "plugin" in config:
        key = "plugin"
    else:
        key = "plugins"

    entries = config.get(key)
    if entries is None:
        entries = []
        config[key] = entries
    elif not isinstance(entries, list):
        raise ConfigError(f"{config_file}: '{key}' must be a JSON array")

    if not any(
        isinstance(entry, str) and _same_path(entry, plugin_target) for entry in entries
    ):
        entries.append(plugin_target)

    result = {
        "plugin_path": plugin_target,
        "plugin_source": source,
        "config": config,
    }

    if dry_run:
        return result

    if config_file.exists():
        backup = Path(str(config_file) + ".bak")
        try:
            shutil.copyfile(config_file, backup)
        except OSError as exc:
            raise ConfigError(f"cannot back up {config_file}: {exc}") from exc
        print(f"bashboy: backup at {backup}", file=sys.stderr)

    atomic_write_text(plugin_path, source)
    atomic_write_text(config_file, json.dumps(config, indent=2, ensure_ascii=False) + "\n")
    return result
